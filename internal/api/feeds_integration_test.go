package api

import (
	"io"
	"net/http"
	"strings"
	"testing"
)

// The catalogue feed needs the store's key, is off by default, and a rotated
// key stops working at once.
func TestProductFeeds(t *testing.T) {
	e := setup(t)
	e.must(200, "POST", "/v1/sites/main/publish", e.adminA, nil)
	e.drain()
	get := func(url string) (int, string) {
		res, err := http.Get(e.srv.URL + url)
		if err != nil {
			t.Fatal(err)
		}
		defer res.Body.Close()
		b, _ := io.ReadAll(res.Body)
		return res.StatusCode, string(b)
	}
	path := func(u string) string { return u[strings.Index(u, "/s/"):] }
	off := e.must(200, "PUT", "/v1/feeds", e.adminA, m{"enabled": false})
	if st, _ := get(path(off["urls"].(map[string]any)["google"].(string))); st != 404 {
		t.Fatalf("feed served while off: %d", st)
	}
	on := e.must(200, "PUT", "/v1/feeds", e.adminA, m{"enabled": true, "googleCategory": "Apparel & Accessories", "key": "elegida-por-el-cliente"})
	urls := on["urls"].(map[string]any)
	g, mt := path(urls["google"].(string)), path(urls["meta"].(string))
	if strings.Contains(g, "elegida-por-el-cliente") {
		t.Fatal("the feed key must be generated by the server")
	}
	st, xml := get(g)
	if st != 200 || !strings.Contains(xml, "<g:id>S1</g:id>") || !strings.Contains(xml, "<g:price>120.00 MXN</g:price>") || !strings.Contains(xml, "<g:sale_price>100.00 MXN</g:sale_price>") ||
		!strings.Contains(xml, "/s/store-a/main/p/p1</g:link>") || !strings.Contains(xml, "Apparel &amp; Accessories") {
		t.Fatalf("google feed = %d\n%s", st, xml[:min(len(xml), 900)])
	}
	if st, csv := get(mt); st != 200 || !strings.HasPrefix(csv, "id,item_group_id,title") || !strings.Contains(csv, "S2,P2,") {
		t.Fatalf("meta feed = %d %s", st, csv[:min(len(csv), 300)])
	}
	if st, _ := get(strings.Split(g, "?")[0] + "?key=otra"); st != 404 {
		t.Fatalf("feed with a wrong key = %d", st)
	}
	if st, _ := get(strings.Replace(g, "/store-a/", "/store-b/", 1)); st != 404 {
		t.Fatalf("store A's key opened store B's feed: %d", st)
	}
	if st, _ := e.do("GET", "/v1/feeds", e.sfA, nil); st != 403 {
		t.Fatalf("a storefront key read the feed settings: %d", st)
	}
	e.must(200, "POST", "/v1/feeds/rotate", e.adminA, nil)
	if st, _ := get(g); st != 404 {
		t.Fatalf("old feed address still works after rotating: %d", st)
	}
}
